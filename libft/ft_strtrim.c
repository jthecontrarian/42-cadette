#include "libft.h"

char *ft_strtrim(char const *s1, char const *set)
{
	size_t	i;
	size_t	j;
	size_t	len;
	char	*p;

	len = 0;
	i = 0;
	while (s1[i] != '\0')
	{
		j = 0;
		while (set[j] != '\0')
		{
			if (s1[i] != set[j])
			{
				len++;
			}
		} 
	}

	p = malloc(len);
	if (!p)
		return (NULL);

	len = 0;
	i = 0;
	while (s1[i] != '\0')
	{
		j = 0;
		while (set[j] != '\0')
		{
			if (s1[i] != set[j])
			{
				p[len] = s1[i];
				len++;
			}
		} 
	}
	return (p);

}